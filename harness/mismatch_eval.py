"""Single-configuration evaluation entry point under mismatch -- called by the search workers,
and by the main loop for final scoring.

Usage:
    python mismatch_eval.py '{"axis":"cor","delta":1.0,"method":"tv","n":4,"file":1}'

Config keys:
    axis    cor | rot | det_scale | ang_jitter | none
    delta   mismatch amount, **reported in physical units**: cor/rot/ang_jitter counted in
            pixels / angular steps, det_scale as a relative amount (0.001 = 1e-3)
    method  tv (official recipe poisson+TV, gamma=20.556) | tgv (our best, tgv2 r0.3 @28)
    iters   default 3000 (exploration) / 5000 (final)
    n       number of images; file=1 exploration / file=0 final (discipline: exploration must
            never touch file 0)

Semantics (the definition of this whole direction, do not change):
    the observation y is a [real LoDoPaB file] generated by the official operator A_true --
    inherently immune to the inverse crime. The method only holds A_belief, the version of
    A_true perturbed by delta, and uses A_belief for the FBP initialization and the data
    fidelity term. delta=0 means "the operator is known" and is the ceiling of this curve.
Output: the last line is JSON.
"""
import os
os.environ.setdefault("CUDA_VISIBLE_DEVICES", "4")
import sys
import json
import warnings
warnings.filterwarnings("ignore")
import numpy as np
import torch
import h5py

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lodopab import psnr, ssim, DATA                    # noqa: E402
from tv_adam import poisson_loss                        # noqa: E402
from regularizers import make_regularizer              # noqa: E402
import mismatch as M                                    # noqa: E402

# physical unit of delta -> keyword for make_operator
AXES = {
    "none":       lambda d: {},
    "cor":        lambda d: {"cor": d * M.det_cell()},        # d = pixels
    "rot":        lambda d: {"rot": d * M.ANG_STEP},          # d = angular steps
    "ang_jitter": lambda d: {"ang_jitter": d * M.ANG_STEP},   # d = angular steps
    "det_scale":  lambda d: {"det_scale": 1.0 + d},           # d = relative amount
}

METHODS = {
    # official TV recipe (the one that cross-checked at 33.83); TGV is the training-free winner
    # selected over two loop rounds, 34.51
    "tv":  {"reg": "aniso_tv", "gamma": 20.556, "kw": {}},
    "tgv": {"reg": "tgv2", "gamma": 28.0, "kw": {"ratio": 0.3}},
}


def main(cfg):
    dev = "cuda:0"
    axis = cfg.get("axis", "none")
    delta = float(cfg.get("delta", 0.0))
    spec = METHODS[cfg.get("method", "tv")]
    n = int(cfg.get("n", 4))
    iters = int(cfg.get("iters", 3000))
    file_idx = int(cfg.get("file", 1))

    op = M.make_operator(device=dev, seed=int(cfg.get("seed", 0)),
                         **AXES[axis](delta))

    with h5py.File(f"{DATA}/observation_test_{file_idx:03d}.hdf5", "r") as h:
        obs = torch.tensor(np.array(h["data"][:n]), dtype=torch.float32)
    with h5py.File(f"{DATA}/ground_truth_test_{file_idx:03d}.hdf5", "r") as h:
        gt = torch.tensor(np.array(h["data"][:n]), dtype=torch.float32)

    po, so = [], []
    for i in range(n):
        y = obs[i].to(dev)
        reg, extra = make_regularizer(spec["reg"], device=dev, **spec["kw"])
        x = op.fbp(y).clone().requires_grad_(True)
        opt = torch.optim.Adam([x] + extra, lr=1e-3)
        best_l, best_x = float("inf"), x.detach().clone()
        for _ in range(iters):
            opt.zero_grad()
            loss = poisson_loss(op.project(x), y) + spec["gamma"] * reg(x)
            loss.backward()
            opt.step()
            l = float(loss.detach())
            if l < best_l:
                best_l, best_x = l, x.detach().clone()
        r = best_x.cpu()
        po.append(psnr(r, gt[i], "adaptive"))
        so.append(ssim(r, gt[i], "adaptive"))

    out = {"axis": axis, "delta": delta, "method": cfg.get("method", "tv"),
           "n": n, "iters": iters, "file": file_idx,
           "psnr": float(np.mean(po)), "ssim": float(np.mean(so)),
           "per_image": [round(p, 2) for p in po],
           "op_params": op.params}
    print(json.dumps(out))
    return out


if __name__ == "__main__":
    main(json.loads(sys.argv[1]))
